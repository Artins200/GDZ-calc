function normalize(o) {
  const vars = (o.vars || []).map((v) => ({
    name: v[0], label: v[1] || v[0], unit: v[2] || '', def: v.length > 3 ? v[3] : null,
  }));
  const kind = o.kind || 'formula';
  const explicit = o.find || null;
  const inferred = vars.find((v) => v.def === null)?.name || null;
  return {
    ...o,
    vars,
    find: kind === 'formula' ? (explicit || inferred || vars[vars.length - 1]?.name || null) : null,
    kind,
    keywords: o.keywords || [],
    desc: o.desc || '',
    bullets: o.bullets || [],
    example: o.example || '',
    dom: o.dom || {},
    page: o.page ?? null,
  };
}

export const FORMULAS = RAW.map(normalize);
export const FORMULA_BY_ID = new Map(FORMULAS.map((f) => [f.id, f]));
export const CHAPTER_BY_ID = new Map(CHAPTERS.map((c) => [c.id, c]));

export function formulaSearch(q) {
  const s = String(q || '').trim().toLowerCase();
  if (!s) return FORMULAS;
  const words = s.split(/\s+/);
  return FORMULAS.map((f) => {
    const hay = [f.id, f.title, f.display, f.desc, f.example, f.sec, ...f.keywords, ...f.bullets].join(' ').toLowerCase();
    let score = 0;
    for (const w of words) if (hay.includes(w)) score += w.length >= 4 ? 2 : 1;
    if (f.title.toLowerCase().includes(s)) score += 6;
    if (f.display.toLowerCase().includes(s)) score += 4;
    return { f, score };
  }).filter((x) => x.score > 0).sort((a, b) => b.score - a.score).map((x) => x.f);
}

