function splitShort(word) {
  const m = SHORT_RE.exec(word);
  if (!m) return null;
  const stem = m[1];
  const ending = m[2] || '';
  if (!SHORT_MASC_RE.test(stem)) return null;
  let gender = 'м. р.', num = 'ед. ч.';
  if (ending === 'а' || ending === 'я') gender = 'ж. р.';
  else if (ending === 'о' || ending === 'ё') gender = 'ср. р.';
  else if (ending === 'ы') { gender = null; num = 'мн. ч.'; }
  return { stem, ending, gender, num };
}

