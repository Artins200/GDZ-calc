const S_RE = /(ся|сь)$/i;

const stripReflexive = (word) => {
  const m = S_RE.exec(word);
  return m ? { bare: word.slice(0, -m[0].length), reflexive: true, suffix: m[0] === 'ся' ? '-ся' : '-сь' } : { bare: word, reflexive: false, suffix: '' };
};

const PERFECTIVE_ROOTS = ['реши', 'куп', 'найд', 'пойм'];

const aspectOf = (code, stem) => {
  if (code === 'дн' || code === 'сн') return { aspect: 'несовершенный', note: 'настоящее время бывает только у глаголов несовершенного вида' };
  // прошедшее время: вид определяем по приставке (в первом приближении)
  if (hasPrefix(stem)) return { aspect: 'совершенный', note: 'есть приставка → совершенный вид' };
  if (PERFECTIVE_ROOTS.some((r) => stem.startsWith(r))) return { aspect: 'совершенный', note: 'глагол совершенного вида (решить, купить… — без приставки, но совершенного вида)' };
  return { aspect: 'несовершенный (скорее всего)', note: 'приставки нет; вид проверьте по глаголу: «делавший» — несов., «сделавший» — сов.' };
};

const feminineOf = (fullMasc) =>
  fullMasc.replace(/(ый|ий|ой)$/, (m) => ({ 'ый': 'ая', 'ий': 'яя', 'ой': 'ая' }[m]));
const neuterOf = (fullMasc) =>
  fullMasc.replace(/(ый|ий|ой)$/, (m) => ({ 'ый': 'ое', 'ий': 'ее', 'ой': 'ое' }[m]));
const pluralOf = (fullMasc) =>
  fullMasc.replace(/(ый|ий|ой)$/, (m) => ({ 'ый': 'ые', 'ий': 'ие', 'ой': 'ые' }[m]));

/** Восстановить полную форму из краткой (для разбора). */
function fullFromShort(short) {
  const { stem, ending, gender, num } = splitShort(short) || {};
  if (!stem) return null;
  let full = null;
  if (stem.endsWith('ен')) full = `${stem.slice(0, -2)}ённый`;           // решена → решённый
  else if (stem.endsWith('н')) full = `${stem}ный`;                        // сделан → сделанный → нужен «нный»
  else if (stem.endsWith('т')) full = `${stem}ый`;                         // открыт → открытый
  if (!full) return null;
  // «…н» + «ный» даёт «…нный» — как и нужно кратким
  if (stem.endsWith('н') && !stem.endsWith('енн')) full = `${stem}ный`;
  if (gender === 'ж. р.') return feminineOf(full);
  if (gender === 'ср. р.') return neuterOf(full);
  if (num === 'мн. ч.') return pluralOf(full);
  return full;
}

/* =========================================================================
 * 4) ГЛАВНОЕ: разбор причастия
 * ========================================================================= */
export function analyzeParticiple(rawWord, opts = {}) {
  const allowShortRules = opts.shortRules !== false; // автоопределение передаёт { shortRules: false }
  const original = String(rawWord ?? '').trim();
  const word = norm(original);
  if (!word) return { ok: false, error: 'Введите слово.' };
  const { bare, reflexive, suffix } = stripReflexive(word);
  // -вши / -ши — окончание деепричастия («умывши(сь)», «несши»), не причастия
  if (/(вши|ши)$/.test(bare)) {
    return { ok: false, error: `«${original}» похоже на деепричастие (что сделав? / что делая?), а не на причастие. Попробуйте режим «Деепричастие».` };
  }

  const finish = (code, opts = {}) => {
    const rz = RAZRYAD[code];
    const full = parseFullEnding(bare);
    const short = splitShort(bare);
    const isShort = !!short && !full; // окончание «отрезало» то, что похоже на краткое
    let ending = full ? full.ending : (short ? (short.ending ? `-${short.ending} (краткая форма)` : 'нулевое (краткая форма)') : '—');
    let gender = full?.gender || short?.gender || null;
    let number = full?.num || short?.num || 'ед. ч.';
    let caseName = full?.case || null;
    const stemForAspect = bare.replace(/(ыми|ими|ых|их|ого|его|ому|ему|ом|ем|ой|ей|ую|юю|ые|ие|ый|ий|ая|яя|ое|ее|ым|им)$/, '');
    const asp = aspectOf(code, stemForAspect);
    // начальная форма — м. р. ед. ч. им. п. полной формы
    let initial;
    if (isShort) {
      initial = fullFromShort(bare) || bare;
    } else if (full) {
      const stem = bare.slice(0, bare.length - full.ending.length);
      let masc = MASC_FORM[full.ending] || (/е$/.test(stem) ? 'ий' : 'ый');
      // окончания -ой/-ей: мужской род той же парадигмы («хранимой» → «хранимый»,
      // «хорошей» → «хороший», «большой» → «большой»)
      if (full.ending === 'ой' || full.ending === 'ей') {
        if (/(ш|ж|щ|ч|ц)$/.test(stem)) masc = full.ending === 'ой' ? 'ой' : 'ий';
        else if (/е$/.test(stem)) masc = 'ий';
        else masc = 'ый';
      }
      initial = stem + masc;
    } else {
      initial = bare;
    }
    const form = isShort ? 'краткая' : 'полная';
    const role = isShort ? 'сказуемое' : 'определение';
    const notes = [...(opts.notes || [])];
    if (isShort && reflexive) notes.push('возвратные причастия краткой формы: «-сь»/«-ся» сохраняется');
    if (!caseName && isShort) notes.push('краткие формы по падежам не изменяются');
    if (!caseName && !isShort) notes.push('падеж не определился автоматически — посмотрите на роль слова в предложении');
    if (reflexive) notes.push(`возвратное причастие (суффикс ${suffix})`);
    notes.push(asp.note);
    if (opts.viaLexicon) notes.push('слово найдено в словаре причастий — разряд определён точно');
    notes.push('проверьте разбор по предложению: полное причастие — обычно определение, краткое — сказуемое');

    const parse = [
      `1. Часть речи: причастие${reflexive ? ` (возвратное, ${suffix})` : ''}.`,
      `2. Начальная форма: ${cap(initial)}.`,
      `3. Постоянные признаки: ${rz.voice}, ${rz.time} времени; ${asp.aspect} вид; ${reflexive ? 'возвратное' : 'невозвратное'}.`,
      `4. Непостоянные признаки: ${form} форма${gender ? `, ${gender}` : ''}, ${number}${caseName && !isShort ? `, ${caseName}` : ''}.`,
      `5. Синтаксическая роль: ${role}.`,
      `6. Образовано от глагола; суффикс причастия — см. разряд.`,
    ];
    return {
      ok: true,
      type: 'причастие',
      word: original,
      initial: cap(initial),
      voice: rz.voice,
      tense: rz.time,
      aspect: asp.aspect,
      reflexive,
      form,
      gender,
      number,
      case: caseName,
      role,
      ending,
      shortWarning: isShort ? 'Краткие причастия совпадают по форме с краткими прилагательными: «комната убрана» (от «убрать») — причастие, «она красива» — прилагательное. Сомневаетесь — задайте вопрос от существительного: комната (какова?) убрана → сказуемое.' : null,
      notes,
      parse,
    };
  };

  // 1) словарь — самый точный путь
  const lex = LEX[bare];
  if (lex) return finish(lex, { viaLexicon: true });

  // 2) отглагольные прилагательные — честно говорим, что это не причастие
  if (ADJ_NOT_PARTICIPLE.has(bare)) {
    return {
      ok: true,
      type: 'отглагольное прилагательное',
      word: original,
      notes: [`«${original}» — как правило, отглагольное прилагательное, а не причастие: образовано от глагола несовершенного вида без приставки и без зависимых слов, поэтому пишется с одной «н» (кроме слов на -ованный/-ёванный).`],
      parse: [`1. Часть речи: отглагольное прилагательное.`, `2. Начальная форма: ${cap(bare)}.`],
    };
  }

  // 3) краткая форма (только страдательное прошедшего)
  if (SHORT_LEX.has(bare)) {
    return finish('сп', { notes: ['краткая форма бывает только у страдательных причастий прошедшего времени; пишется с одной «н»'] });
  }
  if (allowShortRules && !parseFullEnding(bare)) {
    const short = splitShort(bare);
    if (short) {
      // «сделан», «решена», «открыто» — по правилам, с оговоркой про двойников
      return finish('сп', { notes: ['краткая форма бывает только у страдательных причастий прошедшего времени; пишется с одной «н»', 'проверьте по глаголу: краткие причастия совпадают по форме с краткими отглагольными прилагательными'] });
    }
  }

  // 4) правила: суффиксы (сначала на полном слове: «читающ+ий» → -ущ/-ющ + окончание,
  //    потом на основе: «деланн» от «сделанный»)
  const full = parseFullEnding(bare);
  const stemCheck = full ? bare.slice(0, bare.length - full.ending.length) : bare;
  for (const rule of SUFFIX_RULES) {
    if (rule.re.test(bare)) return finish(rule.code, { notes: [rule.note] });
  }
  for (const rule of SUFFIX_RULES) {
    if (rule.re.test(stemCheck)) return finish(rule.code, { notes: [rule.note] });
  }
  // «т» без окончания (краткое: «вымыт») — уже поймано выше; «-щийся/-шься» — возвратные
  if (/(щийся|щаяся|щееся|щиеся)$/.test(bare)) {
    return finish('дн', { notes: ['возвратное действительное причастие настоящего времени'] });
  }
  return {
    ok: false,
    error: `«${original}» не похоже на причастие: не найден ни суффикс (-ущ/-ющ/-ащ/-ящ/-вш/-ш/-ем/-ом/-им/-енн/-ённ/-нн/-т), ни запись в словаре. Возможно, это другая часть речи — попробуйте режим «Авто».`,
  };
}

/* =========================================================================
 * 5) Деепричастие
 * ========================================================================= */
export function analyzeAdverbialParticiple(rawWord, opts = {}) {
  const strict = !!opts.strict; // автоопределение: принимать только знакомые основы
  const original = String(rawWord ?? '').trim();
  const word = norm(original);
  if (!word) return { ok: false, error: 'Введите деепричастие.' };
  const { bare, reflexive } = stripReflexive(word);

  const bySuffix = (re, aspect, note, stemSet) => {
    if (!re.test(bare) || bare.length <= 3) return null;
    const stem = stemOf(bare, re);
    const stemOk = !stemSet || stemSet.has(stem);
    if (strict && !stemOk) return null;
    const aspectFinal = aspect;
    return {
      ok: true,
      type: 'деепричастие',
      word: original,
      aspect: aspectFinal,
      reflexive,
      role: 'обстоятельство',
      validated: stemOk,
      notes: [
        note,
        ...(stemOk ? [] : ['основа не из словаря частых глаголов — проверьте, что это деепричастие, а не другая часть речи']),
        'деепричастие не изменяется; НЕ с деепричастиями пишется раздельно; запятыми выделяется всегда',
      ],
      parse: [
        `1. Часть речи: деепричастие${reflexive ? ' (возвратное)' : ''}.`,
        `2. Начальная форма: ${cap(bare)} (деепричастие не изменяется).`,
        `3. Вид: ${aspectFinal}.`,
        `4. Синтаксическая роль: обстоятельство; образует деепричастный оборот.`,
      ],
    };
  };

  const byV = bySuffix(/(вши|в|ши)$/i, 'совершенный', 'суффиксы -в / -вши / -ши → обычно деепричастие совершенного вида', VSTEM_V);
  if (byV) return byV;
  const byA = bySuffix(/(а|я)$/i, 'несовершенный', 'суффиксы -а / -я → деепричастие несовершенного вида', VSTEM_A);
  if (byA) return byA;
  return { ok: false, error: `«${original}» не похоже на деепричастие (ожидаются суффиксы -а/-я/-в/-вши/-ши: «читая», «решив»).` };
}

/* =========================================================================
 * 6) Глагол (эвристики школьного уровня)
 * ========================================================================= */
export function analyzeVerb(rawWord) {
  const original = String(rawWord ?? '').trim();
  const word = norm(original);
  if (!word) return { ok: false, error: 'Введите глагол.' };
  const { bare, reflexive } = stripReflexive(word);
  const notes = [];
  let tense = null, person = null, gender = null, number = null, aspect, conjugation = null, initial;

  aspect = hasPrefix(bare) ? 'совершенный' : 'несовершенный';
  notes.push(hasPrefix(bare) ? 'есть приставка → совершенный вид' : 'приставки нет → скорее несовершенный вид');

  if (/(ть|ти|чь)$/.test(bare)) {
    tense = 'инфинитив';
    initial = bare;
    notes.push('неопределённая форма (инфинитив): отвечает на вопросы «что делать? / что сделать?»');
  } else if (/л(а|о|и)?$/.test(bare) && /[аеёиоуыя]л(а|о|и)?$/.test(bare)) {
    tense = 'прошедшее';
    const end = bare.match(/(ла|ло|ли|л)$/)[1];
    if (end === 'л') { gender = 'м. р.'; number = 'ед. ч.'; }
    else if (end === 'ла') { gender = 'ж. р.'; number = 'ед. ч.'; }
    else if (end === 'ло') { gender = 'ср. р.'; number = 'ед. ч.'; }
    else { number = 'мн. ч.'; }
    initial = bare.replace(/(ла|ло|ли|л)$/, 'ть');
    notes.push('прошедшее время: суффикс -л-; в прошедшем времени глагол изменяется по родам и числам');
  } else if (/(ете|ите|ете|ёте)$/.test(bare)) {
    tense = 'настоящее (или будущее простое)'; person = '2-е лицо'; number = 'мн. ч.';
    conjugation = bare.endsWith('ите') || bare.endsWith('ёте') ? '2-е спряжение (или ударное -ёте- — 1-е)' : '1-е спряжение';
    initial = bare.replace(/(ете|ите|ёте)$/, 'ть');
    notes.push('окончание -ете/-ите → 2-е лицо мн. ч.; спряжение определите по ударению и инфинитиву');
  } else if (/(ут|ют|ат|ят)$/.test(bare)) {
    tense = 'настоящее (или будущее простое)'; person = '3-е лицо'; number = 'мн. ч.';
    conjugation = /(ат|ят)$/.test(bare) ? '2-е спряжение' : '1-е спряжение';
    initial = bare.replace(/(ут|ют|ат|ят)$/, 'ть');
    notes.push('3-е лицо мн. ч.: -ут/-ют → 1-е спряжение, -ат/-ят → 2-е спряжение');
  } else if (/(ет|ёт|ит)$/.test(bare)) {
    tense = 'настоящее (или будущее простое)'; person = '3-е лицо'; number = 'ед. ч.';
    conjugation = bare.endsWith('ит') ? '2-е спряжение' : '1-е спряжение (или ударное -ёт- — тоже 1-е)';
    initial = bare.replace(/(ет|ёт|ит)$/, 'ть');
    notes.push('3-е лицо ед. ч.: -ет/-ёт → 1-е спряжение, -ит → 2-е спряжение');
  } else if (/(ешь|ёшь|ишь)$/.test(bare)) {
    tense = 'настоящее (или будущее простое)'; person = '2-е лицо'; number = 'ед. ч.';
    conjugation = bare.endsWith('ишь') ? '2-е спряжение' : '1-е спряжение';
    initial = bare.replace(/(ешь|ёшь|ишь)$/, 'ть');
    notes.push('2-е лицо ед. ч.: -ешь/-ёшь → 1-е спряжение, -ишь → 2-е спряжение');
  } else if (/(у|ю)$/.test(bare)) {
    tense = 'настоящее (или будущее простое)'; person = '1-е лицо'; number = 'ед. ч.';
    conjugation = 'спряжение не определяется по этой форме — посмотрите на инфинитив';
    initial = `${bare.slice(0, -1)}ть`;
    notes.push('1-е лицо ед. ч. на -у/-ю: спряжение по этому окончанию не определить');
  } else if (/(ем|им|ём)$/.test(bare)) {
    tense = 'настоящее (или будущее простое)'; person = '1-е лицо'; number = 'мн. ч.';
    conjugation = bare.endsWith('им') ? '2-е спряжение' : '1-е спряжение';
    initial = bare.replace(/(ем|им|ём)$/, 'ть');
    notes.push('1-е лицо мн. ч.: -ем → 1-е спряжение, -им → 2-е спряжение');
  } else {
    return { ok: false, error: `«${original}» не распознано как глагол: нет окончания/суффикса глагола. Укажите инфинитив («читать») или форму с окончанием.` };
  }
  if (reflexive) notes.push('возвратный глагол (-ся/-сь): непереходный');
  const parse = [
    `1. Часть речи: глагол${reflexive ? ' (возвратный)' : ''}.`,
    `2. Начальная форма: ${cap(initial || bare)}.`,
    `3. Постоянные признаки: ${aspect} вид${conjugation ? `, ${conjugation}` : ''}${reflexive ? ', возвратный' : ''}, переходность — по словарю.`,
    `4. Непостоянные признаки: ${tense}${person ? `, ${person}` : ''}${gender ? `, ${gender}` : ''}, ${number}.`,
    `5. Синтаксическая роль: обычно сказуемое.`,
  ];
  return {
    ok: true, type: 'глагол', word: original, initial: cap(initial || bare),
    tense, person, gender, number, aspect, conjugation, reflexive,
    notes, parse,
  };
}

