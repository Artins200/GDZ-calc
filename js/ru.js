function parseFullEnding(word) {
  // сначала длинные окончания
  const sorted = [...FULL_ENDINGS].sort((a, b) => b[0].length - a[0].length);
  for (const [end, info] of sorted) {
    if (word.endsWith(end)) {
      return { ending: end, stem: word.slice(0, -end.length), ...info };
    }
  }
  return null;
}

